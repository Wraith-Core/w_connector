/* ════════════════════════════════════════════════════════════════════════════
 * w_admin · scripts/gen-help-keys.mjs
 * Writes src/help/keys.gen.ts: the HelpKey and LabelKey unions, from locales/help/*.en.json.
 * The kit's `help` prop is typed HelpKey | HelpInline | false, so tsc fails on a missing or
 * misspelt key. Run it after you add a key:   node scripts/gen-help-keys.mjs
 * ════════════════════════════════════════════════════════════════════════════ */

import fs from 'node:fs';
import path from 'node:path';
import { WEB, loadLanguage } from './help-lib.mjs';

const OUT = path.join(WEB, 'src', 'help', 'keys.gen.ts');

const { help, labels, errors } = loadLanguage('en');
if (errors.length) {
  for (const e of errors) console.error(`gen-help-keys: ${e}`);
  process.exit(1);
}

const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const union = (name, keys) => keys.length
  ? `export type ${name} =\n${keys.map((k) => `  | ${q(k)}`).join('\n')};\n`
  : `export type ${name} = never;\n`;

const helpKeys = [...help.keys()].sort();
const labelKeys = [...labels.keys()].sort();

const body = [
  '/* Generated by scripts/gen-help-keys.mjs from locales/help/*.en.json. Do not edit by hand. */',
  '',
  union('HelpKey', helpKeys),
  union('LabelKey', labelKeys),
  `export const HELP_KEY_COUNT = ${helpKeys.length};`,
  '',
].join('\n');

const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
if (prev !== body) {
  const tmp = `${OUT}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, body, 'utf8');
  fs.renameSync(tmp, OUT);
}
console.log(`gen-help-keys: ${helpKeys.length} help keys, ${labelKeys.length} labels${prev === body ? ' (unchanged)' : ''}`);
